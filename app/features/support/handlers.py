import textwrap

from aiogram import F, Router
from aiogram.filters import Command
from aiogram.types import CallbackQuery, Message

from app.features.create_trip.keyboards import start_keyboard


router = Router()


def _help_text() -> str:
    return textwrap.dedent(
        """<b>🤖 KAIRide — бот для совместных поездок</b>

<b>Основные разделы</b>
• <b>Создать поездку</b> — оформить свою поездку:
  └ тип (личный транспорт / такси), откуда (общежитие), куда (здание КАИ), дата, время, кол-во мест, комментарий.
• <b>Найти поездку</b> — поиск по:
  └ общежитию, учебному зданию и дню. В списке только активные поездки с свободными местами.
• <b>Мои поездки</b> — активные и прошедшие поездки:
  └ для организатора: удалить поездку, чат, завершение и опрос;
  └ для пассажира: выйти из поездки, чат, показать свой @username организатору.
• <b>Мой профиль</b> — рейтинг, статистика и дата регистрации.

<b>Команды</b>
• <code>/start</code> — главное меню.
• <code>/create</code> — начать создание поездки.
• <code>/search</code> — начать поиск поездок.
• <code>/profile</code> — открыть профиль.
• <code>/stop_chat</code> — выйти из чата поездки.
• <code>/help</code> — это сообщение.

<b>Рейтинг</b> (начинается с 5.00)
• Пассажир выходит из поездки менее чем за час до отправления:
  └ <b>-0.50</b> к рейтингу пассажира.
• Организатор отменяет поездку менее чем за час, если уже есть пассажиры:
  └ <b>-0.25</b> за каждого пассажира (кроме организатора).
• После завершения поездки организатор может отметить:
  └ опоздавших — <b>-0.25</b> каждому;
  └ не пришедших — <b>-0.75</b> каждому.
• Для поездок на такси пассажиры оценивают, вовремя ли была вызвана машина:
  └ если нет — у организатора <b>-0.50</b>.

Рейтинг никогда не опускается ниже 0.00.

<b>Виртуальный чат по поездке</b>
• Кнопка <b>«💬 Чат по поездке»</b> в активных поездках:
  └ сообщения пересылаются всем участникам поездки (организатору и пассажирам, кроме отправителя).
• /stop_chat — завершить чат и вернуться в главное меню.
• Пассажир может отправить организатору свой @username через кнопку
  <b>«🙋 Показать @username»</b>, чтобы общаться напрямую.

<b>Напоминания</b>
• За 15 минут до поездки бот напоминает организатору и пассажирам о предстоящей поездке.
• За 5 минут до поездки организатор получает напоминание с кнопками:
  └ <b>«✅ Поездка завершена»</b> — запуск опроса и фиксация результатов;
  └ <b>«❌ Отменить поездку»</b> — отмена с учётом рейтинга и уведомлением участников.

<b>Связь по ошибкам и вопросам</b>
Если вы заметили ошибку в работе бота или у вас есть предложения — напишите разработчику:
<b>@emilbad</b>
"""
    )


@router.callback_query(F.data == "support")
async def support_callback(callback: CallbackQuery):
    text = _help_text()
    await callback.message.edit_text(text, reply_markup=start_keyboard)
    await callback.answer()


@router.message(Command("help"))
async def support_command(message: Message):
    text = _help_text()
    await message.answer(text, reply_markup=start_keyboard)

